/**
 * 任务列表标记（`- [ ] 待办` / `- [x] 已完成`）的**唯一一份判据**。
 *
 * ## 为什么它必须单独成一个模块
 *
 * "`[ ]` 算不算任务标记"这件事在本仓库里被问过三次，而且答案曾经有三份：
 *
 * 1. **渲染**：`domain/markdown-core.ts` 的核心规则要据此出复选框
 *    （阅读视图、应用内打印、导出件、静态站点全都走这一条渲染管线）；
 * 2. **画布**：`features/graph/canvas/blocks.ts` 要把 token 画成卡片，而 canvas 里没有 HTML，
 *    它只能自己看 token（ADR-0021）；
 * 3. **编辑器**：`features/editor/cm/live-preview/build.ts` 的所见即所得复选框。
 *
 * 判据散成三份的代价不是"多写几行"，而是**同一篇笔记在不同地方长得不一样**：
 * 一边认 `[X]`、另一边不认，用户看到的是"这两个视图对同一行有不同意见"。
 * 这类分歧不报错，只表现为"看起来不太对"，是最难查的一类问题。所以判据只在这里：
 * 渲染层把**结论**写进 token（`markdown-core.ts` 的 `mn_task_list` 核心规则），
 * 画布读那份结论（`blocks.ts`），编辑器直接调这个函数。
 *
 * ## 判据本身（每一条都是为了不吃掉用户的正文）
 *
 * - **只认行首**：`[x]` 出现在句子中间只是普通文字（"我选 [x] 这一项"）。
 *   匹配任意位置等于把用户手写的方括号当成语法。
 * - **标记后面必须是空白或行尾**：`[x]yz` 不是任务项。
 * - **方括号里只放得下一个字符**：空格（未完成）或 `x`/`X`（已完成）。
 *   `[  ]`（两个空格）不算 —— 与 GFM 的"恰好一个空白字符或 x/X"一致；
 *   放宽它只会把排版用的方括号变成复选框。
 * - **`x` 与 `X` 是同一个状态**：同一个人在同一个文件里两种都会写，
 *   把它们区分成两种状态没有任何好处。
 * - **转义的字面方括号不算**（`- \[x\] 不是任务`）：这一点在这里判不出来 ——
 *   `\[` 被解析之后与真的 `[` 逐字相同。因此渲染层拿**段落原文**来判，
 *   见 `domain/markdown-core.ts` 里 `mn_task_list` 那段关于 `inline.content` 的说明。
 *
 * ## 与编辑器那一侧的口径对账（写在这里，免得下次再对一遍）
 *
 * 编辑器（`features/editor/cm/live-preview/build.ts`）拿到的不是文字，而是 lezer 的 `TaskMarker`
 * 节点，它只做一件事：`/\[[xX]\]/.test(切片)`。**状态映射与本模块逐字一致**
 * （`[ ]` → 未完成、`[x]`/`[X]` → 已完成），也能被本模块表达：`parseTaskMarker('[x]')` 返回
 * `{ checked: true, rest: '' }`。也就是说这一份判据能同时喂两边，编辑器接过来时不需要改语义。
 *
 * 唯一一处**上游**差异不在这个模块里：lezer 的 TaskList 规则是
 * `/^\[[ xX]\][ \t]/`（见 `@lezer/markdown` 的扩展定义）—— 它要求标记后面**必须**还有空格或制表符，
 * 于是 `- [x]`（后面什么都没有的空任务项）在编辑器里不是任务项，而这里认它是
 * （GFM 的口径：标记在段落末尾同样成立；画布从前的正则也是这个口径）。
 * 取舍是"认"：用户写下一个空的待办再回头勾它，是真实存在的用法；
 * 而"编辑器里没画出复选框、阅读视图里画了"这种不一致是可见的、可解释的
 * （标记后面补一个空格即可），反过来则会让待办在导出件里**消失**。
 * 这一条要不要统一由编辑器那一侧决定，本模块只把口径写清楚。
 *
 * ⚠️ 纯函数、零依赖、不碰 `window`/`document`：渲染要在 Web Worker 里跑
 * （`features/preview/render.worker.ts`），这一层跟着一起进 Worker。
 */

/**
 * 判据本体，就这一条正则。
 *
 * ⚠️ 它**故意**长得很窄：只回答"这段文字以一个任务标记开头吗、标记之后还剩什么"，
 * 不回答"这段文字在整篇文档的什么位置" —— 位置由调用方保证（渲染层看的是列表项第一段的
 * 第一个文字 token，画布看的是 `list_item_open` 上的结论）。
 */
const TASK_MARKER = /^\[([ xX])\](?:\s+|$)/

/** 任务标记的解析结果。 */
export interface TaskMarker {
  /** `[x]` / `[X]` 已完成，`[ ]` 未完成。 */
  checked: boolean
  /**
   * 标记**之后**的正文（标记本身与紧跟其后的空白都已经去掉）。
   *
   * 为什么连那个空白一起去掉：标记换成复选框之后，这个空格属于"标记的一部分"，
   * 留着它会在复选框与文字之间多出一条缝（复选框自己已经带了外边距）。
   * 后面什么都没写的任务项（`- [ ]`）在这里得到空串 —— 它**依然是任务项**，
   * 调用方必须照常画出一个空的复选框，否则等于把用户写下的待办删了。
   */
  rest: string
}

/**
 * 解析一段文字开头的任务标记；不是任务项返回 `null`。
 *
 * 判据的最后一条（"只认行首"）就落在正则的 `^` 上：传进来的必须是**行首那一段文字**
 * （渲染层传的是列表项第一段的第一个文字 token，不是整段正文）。
 */
export function parseTaskMarker(text: string): TaskMarker | null {
  const match = TASK_MARKER.exec(text)
  if (match === null) return null
  // 方括号里只能是空格 / `x` / `X`（正则已经保证），所以"是不是 x/X"就是"勾没勾上"
  const state = match[1]
  return { checked: state === 'x' || state === 'X', rest: text.slice(match[0].length) }
}

