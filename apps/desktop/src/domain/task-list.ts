/**
 * 渲染层写在 `list_item_open` token 上的**内部属性名**。
 *
 * 为什么需要它：判据只有一处能算（核心规则，那里才知道"这是不是任务项"），
 * 但**消费者有两个** —— 渲染器要据此出复选框，画布要据此决定卡片上画实心的还是空心的勾选框。
 * 两者看到的是同一个 token 流，所以结论就写在 token 上。
 *
 * ⚠️ 它**不进 HTML**：渲染器在拼 `<li>` 之前会把它摘掉（`markdown-core.ts` 的
 * `list_item_open` 规则）。真漏了也不致命 —— 净化白名单里没有这个名字，
 * DOMPurify 会把它连同其它不认识的属性一起剥掉（这也是它**不叫** `data-mn-*` 的原因：
 * `data-mn-*` 在这个仓库里的含义恰好是"必须熬过净化、下游要读"）。
 */
export const TASK_CHECKED_ATTR = 'mn-task-checked'

/**
 * 属性值的写端。
 *
 * 用 `'1'`/`'0'` 而不是 `''`/`'1'`：空字符串属性看起来像布尔属性，
 * 而这里的三态（有/无属性 = 是不是任务项）已经很绕，值再暧昧下去读代码的人会被绕进去。
 */
export function taskCheckedValue(checked: boolean): string {
  return checked ? '1' : '0'
}

/**
 * 属性值的读端；读不出来返回 `undefined`。
 *
 * ⚠️ `undefined` 的含义是"**这不是任务项**"，不是"未完成" ——
 * 未完成是 `false`。把两者混起来，画布会把普通列表项也画上勾选框。
 */
export function taskCheckedFromAttr(value: string | null): boolean | undefined {
  if (value === '1') return true
  if (value === '0') return false
  return undefined
}
