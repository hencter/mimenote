/**
 * 标签面板输入框的解析规则。
 *
 * 为什么单独一个文件而不是写在组件里：这条规则是**用户可见的契约**（README 与 ADR-0006
 * 都要写明"一次能输入几个、怎么分隔"），写在纯函数里才能被单独钉住。
 *
 * 规则（刻意保守）：
 *
 * 1. **逗号分隔**：半角 `,` 与全角 `，` 都算分隔符 —— 与 frontmatter 里
 *    `tags: 甲, 乙` 的既有口径一致（`mn_core::frontmatter` 的标量标签就是按逗号切）；
 * 2. **不用空格分隔**：`normalize_tag` 明确允许标签里带空格（`中文 标签` 是一个标签），
 *    按空格切会把用户合法的一个标签拆成两个 —— 这种"看起来聪明"的规则最难解释；
 * 3. 每个标签去首尾空白；空项（连续逗号、只有一个逗号）直接丢掉；
 * 4. **开头的 `#` 由宿主清理**（`normalize_tag` 的口径），这里不重复一套判同规则。
 */
export function parseTagInput(raw: string): string[] {
  return raw
    .split(/[,，]/u)
    .map((part) => part.trim())
    .filter((part) => part !== '')
}
